const purchaseSchema = z.object({
    unit_id: z.string()
        .min(1, "وحدة الشراء مطلوبة"),

    unit_name: z.string()
        .trim()
        .min(1, "اسم وحدة الشراء مطلوب"),

    price: z.number()
        .nonnegative("سعر الشراء لا يمكن أن يكون سالباً"),

    quantity: z.number()
        .nonnegative("كمية المخزون لا يمكن أن تكون سالبة"),

    base_quantity: z.number()
        .nonnegative("كمية المخزون الأساسية لا يمكن أن تكون سالبة")
});



const addProductSchema = z.object({
    product: productSchema,
    purchase: purchaseSchema,
    units: z.array(unitSchema)
        .min(1, "يجب إضافة وحدة واحدة على الأقل")
}).superRefine((data, ctx) => {

    const { product, purchase, units } = data;

    // =========================
    // التحقق من الوحدة الأساسية
    // =========================

    const baseUnits = units.filter(unit => unit.is_base_unit);

    if (baseUnits.length !== 1) {
        ctx.addIssue({
            code: z.ZodIssueCode.custom,
            path: ["units"],
            message: "يجب أن يحتوي المنتج على وحدة أساسية واحدة فقط"
        });
    }

    const baseUnit = baseUnits[0];

    if (baseUnit) {

        if (baseUnit.conversion_factor !== 1) {
            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["units"],
                message: "معامل تحويل الوحدة الأساسية يجب أن يكون 1"
            });
        }

        if (baseUnit.contains_unit_id !== null) {
            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["units"],
                message: "الوحدة الأساسية لا يمكن أن تحتوي على وحدة أخرى"
            });
        }

        if (baseUnit.contains_quantity !== null) {
            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["units"],
                message: "الوحدة الأساسية لا يمكن أن تحتوي على كمية"
            });
        }

        if (baseUnit.contains_unit_name !== null) {
            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["units"],
                message: "الوحدة الأساسية لا يمكن أن تحتوي على وحدة"
            });
        }
    }

    // =========================
    // أسماء الوحدات
    // =========================

    const unitNames = new Set();

    for (const unit of units) {

        const normalizedName = unit.unit_name.trim().toLowerCase();

        if (unitNames.has(normalizedName)) {
            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["units"],
                message: `اسم الوحدة "${unit.unit_name}" مكرر`
            });
        }

        unitNames.add(normalizedName);
    }

    // =========================
    // الباركودات
    // =========================

    const barcodes = new Set();

    for (const unit of units) {

        if (!unit.barcode) continue;

        if (barcodes.has(unit.barcode)) {
            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["units"],
                message: `الباركود "${unit.barcode}" مستخدم أكثر من مرة`
            });
        }

        barcodes.add(unit.barcode);
    }

    // =========================
    // التحقق من الوحدات الأب
    // =========================

    const unitMap = new Map(
        units.map(unit => [unit.id, unit])
    );

    for (const unit of units) {

        if (unit.is_base_unit) continue;

        if (!unit.contains_unit_id) {
            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["units"],
                message: `الوحدة "${unit.unit_name}" يجب أن تحتوي على وحدة`
            });

            continue;
        }

        const parentUnit = unitMap.get(unit.contains_unit_id);

        if (!parentUnit) {
            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["units"],
                message: `الوحدة "${unit.unit_name}" تحتوي على وحدة غير موجودة`
            });

            continue;
        }

        if (!unit.contains_quantity) {
            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["units"],
                message: `يجب تحديد كمية الوحدة "${unit.unit_name}"`
            });

            continue;
        }

        // =========================
        // حساب معامل التحويل
        // =========================

        const expectedConversion =
            unit.contains_quantity *
            parentUnit.conversion_factor;

        if (unit.conversion_factor !== expectedConversion) {
            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["units"],
                message:
                    `معامل تحويل الوحدة "${unit.unit_name}" غير صحيح`
            });
        }

        // منع الوحدة من احتواء نفسها
        if (unit.contains_unit_id === unit.id) {
            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["units"],
                message: `الوحدة "${unit.unit_name}" لا يمكن أن تحتوي نفسها`
            });
        }
    }

    // =========================
    // التحقق من وحدة الشراء
    // =========================

    const purchaseUnit = unitMap.get(purchase.unit_id);

    if (!purchaseUnit) {

        ctx.addIssue({
            code: z.ZodIssueCode.custom,
            path: ["purchase", "unit_id"],
            message: "وحدة الشراء غير موجودة ضمن وحدات المنتج"
        });

    } else {

        // التحقق من اسم الوحدة
        if (purchase.unit_name !== purchaseUnit.unit_name) {

            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["purchase", "unit_name"],
                message: "اسم وحدة الشراء غير متطابق"
            });
        }

        // حساب المخزون الأساسي
        const expectedBaseQuantity =
            purchase.quantity *
            purchaseUnit.conversion_factor;

        if (purchase.base_quantity !== expectedBaseQuantity) {

            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["purchase", "base_quantity"],
                message: "كمية المخزون الأساسية غير صحيحة"
            });
        }

        // مقارنة مخزون المنتج
        if (product.stock_quantity !== purchase.base_quantity) {

            ctx.addIssue({
                code: z.ZodIssueCode.custom,
                path: ["product", "stock_quantity"],
                message: "مخزون المنتج لا يطابق كمية المخزون الأساسية"
            });
        }
    }
});
