export const updateItem = async (req, res) => {
  const itemId = Number(req.query.item_id);
  const transaction = new sql.Transaction(pool);
  try {
    const token = req.headers.authorization;
    if (!token) {
      throw new SystemError("إنتهت صلاحية الجلسة , الرجاء تسجيل الدخول مرة أخرى", 401);
    }
    await checkToken(token);

    const body = req.body;

    const needToAutoGeneratedBarcode = body.auto_generated_barcode === "1";

    let barcode;


    const schema = buildProductSchema(false);

    const rawData = {
      name: body.name,
      category_id: body.category_id,
      price: body.price || null,
      barcode: body.barcode,
      stock: Number(body.stock) || 0,
    };
    const validated = schema.safeParse(rawData);

    if (!validated.success) {
      const errors = validated.error.issues.map((err) => ({
        field: err.path.join("."),
        message: err.message,
      }));

      return res.status(400).json({
        success: false,
        errors,
      });
    }

    barcode = validated.data.barcode;


    if (barcode) {
      const existItem = await checkBarcode(barcode);
      if (existItem && existItem.id !== itemId) {
        throw new SystemError("خطأ : الباركود المدخل مُعرف لصنف آخر , الرجاء إدخال باركود مختلف ", 409);
      }
    }


    if (needToAutoGeneratedBarcode) {
      barcode = await generateUniqueBarcode()
    }

    await transaction.begin();


    await transaction.request()
      .input("name", sql.NVarChar, validated.data.name)
      .input("barcode", sql.NVarChar, barcode)
      .input("stock", sql.Int, validated.data.stock)
      .input("category_id", sql.Int, validated.data.category_id)
      .input("price", sql.Decimal(10, 2), validated.data.price)
      .input("id", sql.Int, itemId)
      .query(`
        UPDATE items
        SET name = @name, barcode = @barcode, category_id = @category_id, price = @price, stock = @stock
        WHERE id = @id
      `)
      ;


    await transaction.commit();

    return res.status(StatusCode.Ok).json({
      message: "تم تعديل الصنف بنجاح"
    });

  } catch (e) {
    try {
      await transaction.rollback();
    } catch (err) {
      console.error(err);
    }


    if (e?.originalError?.info?.message?.includes("Violation of UNIQUE KEY constraint")) {
      return res.status(409).json({
        message: "إسم الصنف موجود مسبقأ الرجاء إدخال إسم آخر"
      });
    }

    return res.status(e.status || 500).json({
      success: false,
      message: e.message || "حدث خطأ غير معروف",
    });
  }
}


